"""Main-payload vectors for safety.md rule 3, shared by both implementations of its checks:
wisp-ota's `checkMainPayload` (packages/wisp-ota/src/main-payload-vectors.test.ts) and
install-wisp's port (wisp_w18/native.py, tests/test_install_wisp.py). Each vector is a payload
(preamble + image) and the guard ids that must fail on it; both suites expand the same JSON and
must report exactly those ids.

The JSON is sparse: `length` bytes of zeros with `patches` [offset, hex] applied (the preamble CRC
included), so payloads up to the 0x7F8000 ceiling stay small in the repository.

    python3 -I apps/wisp-recovery/tests/rule3_vectors.py --write   # regenerate the JSON
"""

from __future__ import annotations

import json
import struct
import sys
import zlib
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
JSON = REPO / "packages/wisp-ota/src/testing/main-payload-vectors.json"
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from wisp_w18 import native  # noqa: E402

LOAD = 0x0043_8000
SIZE = 0x4000


def payload(app_size=SIZE, sp=0x2007FB00, reset=LOAD + 0x201, flags=0x04, data_type=0xCB, load=LOAD,
            declared_delta=0, reserved=(0, 0, 0, 0), stale_crc=False) -> tuple[int, dict[int, bytes]]:
    total = 0x20 + app_size
    body = bytearray(total)
    struct.pack_into("<I", body, 0x00, (flags << 24) | ((total + declared_delta) & 0xFFFFFF))
    struct.pack_into("<II", body, 0x08, *reserved[:2])
    struct.pack_into("<II", body, 0x10, data_type, load)
    struct.pack_into("<II", body, 0x18, *reserved[2:])
    if app_size >= 8:
        struct.pack_into("<II", body, 0x20, sp, reset)
    for i in range(8, min(0x40, app_size), 4):
        struct.pack_into("<I", body, 0x20 + i, LOAD + 0x301)
    if app_size > 0x200:
        body[0x20 + 0x200 : 0x20 + 0x208] = b"WISPTEST"
    crc = zlib.crc32(body[8:])
    struct.pack_into("<I", body, 0x04, crc ^ 1 if stale_crc else crc)
    patches = {}
    for at in range(0, min(total, 0x240), 16):  # the preamble, vectors and the marker; the rest is zero
        chunk = bytes(body[at : at + 16])
        if any(chunk):
            patches[at] = chunk
    return total, patches


def ending_at(end: int) -> int:
    return end - LOAD


RECIPES = {
    "valid": {},
    "flags-0x05": {"flags": 0x05},
    "data-type": {"data_type": 0xCC},
    "reserved-word": {"reserved": (0, 1, 0, 0)},
    "load-0x448000": {"load": 0x0044_8000},
    "load-in-the-bootloader": {"load": 0x0043_0000},
    "declared-larger": {"declared_delta": 16},
    "declared-smaller": {"declared_delta": -16},
    "too-small": {"app_size": 0x30},
    "shorter-than-preamble-and-vectors": {"app_size": 4},
    "declared-end-past-the-ceiling": {"app_size": ending_at(0x007F_8000), "declared_delta": 16},
    "ends-at-the-ceiling": {"app_size": ending_at(0x007F_8000)},
    "past-the-ceiling": {"app_size": ending_at(0x007F_8000) + 16},
    "reaches-the-flag": {"app_size": ending_at(0x007F_E000) + 16},
    "sp-below-sram": {"sp": 0x1FFF_0000},
    "sp-in-mram": {"sp": 0x0050_0000},
    "sp-past-sram": {"sp": 0x2038_0008},
    "sp-0x20400000": {"sp": 0x2040_0000},  # image.py's old bound would pass it
    "sp-unaligned": {"sp": 0x2007_FB04},
    "sp-at-the-sram-base": {"sp": 0x2000_0000},
    "sp-at-the-sram-top": {"sp": 0x2038_0000},
    "reset-even": {"reset": LOAD + 0x200},
    "reset-past-the-end": {"reset": LOAD + SIZE + 1},
    "reset-below-the-image": {"reset": 0x0041_0001},
    "reset-into-the-vectors": {"reset": LOAD + 0x9},
    "stale-crc": {"stale_crc": True},
}


def expand(vector: dict) -> bytes:
    data = bytearray(vector["length"])
    for at, chunk in vector["patches"]:
        data[at : at + len(chunk) // 2] = bytes.fromhex(chunk)
    return bytes(data)


def build() -> list[dict]:
    out = []
    for name, recipe in RECIPES.items():
        length, patches = payload(**recipe)
        vector = {"name": name, "length": length, "patches": [[at, chunk.hex()] for at, chunk in patches.items()]}
        failed = sorted(r["id"] for r in native.check_main_payload(expand(vector)) if not r["ok"])
        out.append({**vector, "failed": failed})
    return out


def text() -> str:
    return json.dumps({"comment": "Generated by apps/wisp-recovery/tests/rule3_vectors.py; do not edit.",
                       "vectors": build()}, indent=1) + "\n"


if __name__ == "__main__":
    if sys.argv[1:] == ["--write"]:
        JSON.write_text(text())
        print(f"wrote {JSON}")
    else:
        print(text())
