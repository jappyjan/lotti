"""Writes src/display/boot_font.h: the four glyphs of "Wisp" as a Wisp bitmap font (protocol.md,
resource type 3), drawn by native-1's boot screen through wisp-core's text path.

    python3 -I scripts/gen_boot_font.py            # rewrite the header
    python3 -I scripts/gen_boot_font.py --check    # exit 1 if the committed header differs

A 5x7 pixel design (p descends 2 rows), each pixel SCALE x SCALE, full coverage (15)."""
import struct
import sys
from pathlib import Path

SCALE = 8
GLYPHS = {
    "W": ["X...X", "X...X", "X...X", "X.X.X", "X.X.X", "XX.XX", "X...X"],
    "i": ["..X..", ".....", ".XX..", "..X..", "..X..", "..X..", ".XXX."],
    "p": [".....", ".....", "XXXX.", "X...X", "X...X", "X...X", "XXXX.", "X....", "X...."],
    "s": [".....", ".....", ".XXXX", "X....", ".XXX.", "....X", "XXXX."],
}
CELL_ROWS = 7  # rows above the baseline
OUT = Path(__file__).resolve().parents[1] / "src/display/boot_font.h"


def raw4(rows: list[str]) -> tuple[int, int, bytes]:
    w, h = len(rows[0]) * SCALE, len(rows) * SCALE
    stride = (w + 1) // 2
    out = bytearray(stride * h)
    for y in range(h):
        for x in range(w):
            if rows[y // SCALE][x // SCALE] == "X":
                out[y * stride + x // 2] |= 0xF0 if x % 2 == 0 else 0x0F
    return w, h, bytes(out)


def font() -> bytes:
    line_h, baseline = (CELL_ROWS + 3) * SCALE, CELL_ROWS * SCALE
    table, bitmaps = b"", b""
    for ch in sorted(GLYPHS, key=ord):
        w, h, bits = raw4(GLYPHS[ch])
        table += struct.pack("<IBBbbBI", ord(ch), w, h, 0, -baseline, w + SCALE, len(bitmaps))
        bitmaps += bits
    return struct.pack("<BBH", line_h, baseline, len(GLYPHS)) + table + bitmaps


def header() -> str:
    data = font()
    lines = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + "," for i in range(0, len(data), 16)]
    body = "\n".join("\t" + line for line in lines)
    return f"""/*
 * SPDX-License-Identifier: MIT
 *
 * Generated by scripts/gen_boot_font.py; do not edit. "Wisp" in a {SCALE}x-scaled 5x7 pixel design,
 * as a Wisp bitmap font (protocol.md, resource type 3), {len(data)} bytes.
 */
#ifndef WISP_BOOT_FONT_H
#define WISP_BOOT_FONT_H

#include <stdint.h>

#define WISP_BOOT_FONT_ADVANCE {5 * SCALE + SCALE}
#define WISP_BOOT_FONT_LINE_H {(CELL_ROWS + 3) * SCALE}

static const uint8_t wisp_boot_font[{len(data)}] = {{
{body}
}};

#endif /* WISP_BOOT_FONT_H */
"""


if __name__ == "__main__":
    text = header()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(font())} bytes of font)")
