#!/usr/bin/env python3
"""Generates include/wisp/msgs.h and src/msgs.c from spec.py.

usage: gen_c.py [--check]   (--check fails if the checked-in files are stale)
"""
import pathlib
import sys

from spec import ERROR, MESSAGES, SERVICES, STRUCTS, fixed_size, parse_fields

ROOT = pathlib.Path(__file__).resolve().parent.parent
KINDS = {"req": "WISP_KIND_REQ", "rsp": "WISP_KIND_RSP", "evt": "WISP_KIND_EVT"}
CTYPES = {"u8": "uint8_t", "i8": "int8_t", "u16": "uint16_t", "i16": "int16_t", "u32": "uint32_t",
          "i32": "int32_t", "u64": "uint64_t", "bytes": "wisp_bytes", "utf8": "wisp_bytes", "items": "wisp_bytes"}
ARRAYS = {"str16": ("char", 17), "hash16": ("uint8_t", 16), "sha256": ("uint8_t", 32)}
HEADER = "/* Generated by tools/gen_c.py from tools/spec.py. Do not edit. MIT License, Wisp contributors. */\n"


def layouts():
    """(symbol, desc name, svc, op, kind, fields) for every layout, structs first."""
    out = [(n, n, 0, 0, "WISP_KIND_STRUCT", parse_fields(f)) for n, f in STRUCTS.items()]
    out.append(("error", "error", 0, 0, "WISP_KIND_ERR", parse_fields(ERROR)))
    for svc, op, kind, name, fields in MESSAGES:
        out.append((f"{svc}_{name}_{kind}", f"{svc}/{name}", SERVICES[svc], op, KINDS[kind], parse_fields(fields)))
    return out


def gen_h():
    lines = [HEADER, "#ifndef WISP_MSGS_H", "#define WISP_MSGS_H", "", '#include "msg.h"', ""]
    lines += [f"#define WISP_SVC_{s.upper()} 0x{i:02x}" for s, i in SERVICES.items()]
    lines.append("")
    seen = set()
    for svc, op, _, name, _ in MESSAGES:
        if (svc, name) not in seen:
            seen.add((svc, name))
            lines.append(f"#define WISP_OP_{svc.upper()}_{name.upper()} {op}")
    lines.append("")
    for sym, _, _, _, _, fields in layouts():
        if fields:
            lines.append("typedef struct {")
            for fname, ftype, _ in fields:
                if ftype in ARRAYS:
                    ctype, n = ARRAYS[ftype]
                    lines.append(f"    {ctype} {fname}[{n}];")
                else:
                    lines.append(f"    {CTYPES[ftype]} {fname};")
            lines.append(f"}} wisp_{sym}_t;")
        lines.append(f"extern const wisp_desc wisp_{sym}_desc;")
        lines.append("")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def gen_c():
    lines = [HEADER, "#include <stddef.h>", "", '#include "wisp/msgs.h"', ""]
    table = []
    for sym, name, svc, op, kind, fields in layouts():
        fields_ref = "NULL"
        if fields:
            lines.append(f"static const wisp_field {sym}_fields[] = {{")
            for fname, ftype, item in fields:
                item_ref = f"&wisp_{item}_desc" if item else "NULL"
                lines.append(f'    {{"{fname}", WISP_T_{ftype.upper()}, offsetof(wisp_{sym}_t, {fname}), {item_ref}}},')
            lines.append("};")
            fields_ref = f"{sym}_fields"
        size = f"sizeof(wisp_{sym}_t)" if fields else "0"
        lines.append(f'const wisp_desc wisp_{sym}_desc = {{"{name}", {svc}, {op}, {kind}, {len(fields)}, '
                     f"{fixed_size(fields)}, {size}, {fields_ref}}};")
        lines.append("")
        if kind not in ("WISP_KIND_STRUCT", "WISP_KIND_ERR"):
            table.append(f"    &wisp_{sym}_desc,")
    lines += ["const wisp_desc *const wisp_msg_table[] = {", *table, "};",
              "const size_t wisp_msg_table_len = sizeof wisp_msg_table / sizeof wisp_msg_table[0];"]
    return "\n".join(lines) + "\n"


def main():
    outputs = {ROOT / "include/wisp/msgs.h": gen_h(), ROOT / "src/msgs.c": gen_c()}
    if "--check" in sys.argv:
        stale = [str(p) for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        if stale:
            sys.exit("stale, run tools/gen_c.py: " + ", ".join(stale))
        return
    for path, text in outputs.items():
        path.write_text(text)


if __name__ == "__main__":
    main()
