// Bundles the JavaScriptCore entries into single IIFE files (no imports, no
// Node globals). dist/wisp-ota.js ships in the iOS app; dist/wisp-ota-fake-temple.js
// is for tests and the Simulator only.
import { build } from 'esbuild';

const common = {
  bundle: true,
  format: 'iife',
  platform: 'neutral',
  target: 'es2022',
  legalComments: 'inline',
  logLevel: 'warning',
  minify: false,
};

await build({
  ...common,
  entryPoints: ['src/jsc-entry.ts'],
  outfile: 'dist/wisp-ota.js',
  banner: {
    js: '// @wisp/ota for JavaScriptCore — generated by packages/wisp-ota-jsc (MIT). Do not edit.',
  },
});
await build({
  ...common,
  entryPoints: ['src/fake-temple-entry.ts'],
  outfile: 'dist/wisp-ota-fake-temple.js',
  banner: {
    js: '// wisp-ota fake stock temple for tests — generated by packages/wisp-ota-jsc (MIT). Not for device builds.',
  },
});
